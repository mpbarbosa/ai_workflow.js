/**
 * Integration test – listDirectoryRecursive must not traverse node_modules
 * @description Regression test for the bug where nested node_modules directories
 *   (e.g. src/lambda/geocode-reverse/node_modules/) were fully traversed by
 *   listDirectoryRecursive even when callers passed no exclude options.
 *
 *   Fix: NEVER_TRAVERSE_DIRS constant in file_operations.js merges well-known
 *   third-party directory names into the exclude set at every recursive depth.
 *
 * @version 1.0.0
 */

import { describe, test, expect, beforeEach, afterEach } from '@jest/globals';
import fs from 'fs/promises';
import path from 'path';
import os from 'os';
import { FileOperations } from '../../src/lib/file_operations.js';

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

async function writeFile(dir, relPath, content = 'x') {
  const fullPath = path.join(dir, relPath);
  await fs.mkdir(path.dirname(fullPath), { recursive: true });
  await fs.writeFile(fullPath, content);
}

// ---------------------------------------------------------------------------
// Suite
// ---------------------------------------------------------------------------

describe('Integration: listDirectoryRecursive – nested node_modules exclusion', () => {
  let tempDir;
  let fileOps;

  beforeEach(async () => {
    tempDir = await fs.mkdtemp(path.join(os.tmpdir(), 'ai_workflow_nm_integration_'));
    fileOps = new FileOperations();

    // Project structure that mirrors the reported scenario:
    //   src/
    //     lambda/
    //       geocode-reverse/
    //         index.js                    ← should appear in results
    //         node_modules/               ← must NOT be traversed
    //           some-dep/
    //             index.js               ← must NOT appear in results
    //   src/utils.js                      ← should appear in results
    //   node_modules/                     ← must NOT be traversed (root-level)
    //     root-dep/
    //       index.js                      ← must NOT appear in results

    await writeFile(tempDir, 'src/lambda/geocode-reverse/index.js');
    await writeFile(tempDir, 'src/lambda/geocode-reverse/node_modules/some-dep/index.js');
    await writeFile(tempDir, 'src/utils.js');
    await writeFile(tempDir, 'node_modules/root-dep/index.js');
  });

  afterEach(async () => {
    await fs.rm(tempDir, { recursive: true, force: true });
  });

  test('excludes root-level node_modules by default (no options)', async () => {
    const files = await fileOps.listDirectoryRecursive(tempDir);
    const hasNodeModulesFile = files.some((f) => f.includes('node_modules'));
    expect(hasNodeModulesFile).toBe(false);
  });

  test('excludes nested node_modules (src/lambda/geocode-reverse/node_modules/) by default', async () => {
    const files = await fileOps.listDirectoryRecursive(tempDir);
    const nested = files.find((f) => f.includes(path.join('geocode-reverse', 'node_modules')));
    expect(nested).toBeUndefined();
  });

  test('includes project source files that are not inside node_modules', async () => {
    const files = await fileOps.listDirectoryRecursive(tempDir);
    const sourceFiles = files.map((f) => path.relative(tempDir, f));
    expect(sourceFiles).toContain(path.join('src', 'lambda', 'geocode-reverse', 'index.js'));
    expect(sourceFiles).toContain(path.join('src', 'utils.js'));
  });

  test('allowAll: true overrides default exclusions and traverses node_modules', async () => {
    const files = await fileOps.listDirectoryRecursive(tempDir, { allowAll: true });
    const hasNodeModulesFile = files.some((f) => f.includes('node_modules'));
    expect(hasNodeModulesFile).toBe(true);
  });

  test('caller-provided exclude list is respected alongside defaults', async () => {
    // Create an extra directory that should be excluded via caller option
    await writeFile(tempDir, 'dist/bundle.js');

    const files = await fileOps.listDirectoryRecursive(tempDir, { exclude: ['dist'] });
    const hasDist = files.some((f) => f.includes(path.join(tempDir, 'dist')));
    const hasNodeModulesFile = files.some((f) => f.includes('node_modules'));

    expect(hasDist).toBe(false);
    expect(hasNodeModulesFile).toBe(false);
  });
});
